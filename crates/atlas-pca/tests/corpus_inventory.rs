//! The inventory of every differential corpus in test-data/: its case total and, per function, its case count, pinned in
//! tests/corpus-inventory.json. A replay test that silently skips part of a corpus cannot hide behind a changed corpus: a regenerated corpus
//! (more cases, a new function, a dropped one) fails here until the inventory is refreshed on purpose (PCA_UPDATE_CORPUS_INVENTORY=1) and the
//! replay tests are checked against the new shape. A corpus with no entry fails too.
use std::collections::BTreeMap;

use atlas_pca::serde_json::{json, Map, Value};

const PINNED: &str = include_str!("corpus-inventory.json");

fn read(path: &std::path::Path) -> Option<Value> {
    let o = std::process::Command::new("gzip").arg("-dc").arg(path).output().ok()?;
    if !o.status.success() {
        return None;
    }
    let text = String::from_utf8(o.stdout).ok()?;
    // a lone surrogate escape is not a Rust string: the inventory counts the cases, not their text
    let text = scrub_lone_surrogates(&text);
    atlas_pca::serde_json::from_str(&text).ok()
}

fn scrub_lone_surrogates(s: &str) -> String {
    // \uD800..\uDFFF escapes that do not form a pair become U+FFFD (the shape only is counted here)
    let b = s.as_bytes();
    let mut out = String::with_capacity(s.len());
    let mut i = 0;
    let hex = |at: usize| -> Option<u32> { std::str::from_utf8(b.get(at..at + 4)?).ok().and_then(|h| u32::from_str_radix(h, 16).ok()) };
    while i < b.len() {
        if b[i] == b'\\' && b.get(i + 1) == Some(&b'u') {
            if let Some(v) = hex(i + 2) {
                if (0xD800..0xDC00).contains(&v) {
                    let pair = b.get(i + 6) == Some(&b'\\')
                        && b.get(i + 7) == Some(&b'u')
                        && hex(i + 8).is_some_and(|w| (0xDC00..0xE000).contains(&w));
                    if pair {
                        out.push_str(&s[i..i + 12]);
                        i += 12;
                    } else {
                        out.push_str("\\ufffd");
                        i += 6;
                    }
                    continue;
                }
                if (0xDC00..0xE000).contains(&v) {
                    out.push_str("\\ufffd");
                    i += 6;
                    continue;
                }
            }
        }
        let ch = s[i..].chars().next().unwrap();
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

fn shape(doc: &Value) -> Option<Value> {
    let cases = doc.get("cases")?.as_array()?;
    let mut fns: BTreeMap<String, u64> = BTreeMap::new();
    for c in cases {
        if let Some(f) = c.get("fn").and_then(Value::as_str) {
            *fns.entry(f.to_string()).or_default() += 1;
        }
    }
    Some(json!({"count": cases.len(), "fns": fns}))
}

#[test]
fn every_corpus_matches_its_pinned_inventory() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("test-data");
    let mut actual: BTreeMap<String, Value> = BTreeMap::new();
    for e in std::fs::read_dir(&dir).expect("test-data").flatten() {
        let name = e.file_name().to_string_lossy().to_string();
        let Some(stem) = name.strip_suffix(".json.gz") else { continue };
        // the generated half of a split corpus is built in CI and checked by its own replay test
        if stem.ends_with("-gen") {
            continue;
        }
        if let Some(s) = read(&e.path()).as_ref().and_then(shape) {
            actual.insert(stem.to_string(), s);
        }
    }
    if std::env::var("PCA_UPDATE_CORPUS_INVENTORY").is_ok_and(|v| v == "1") {
        let mut m = Map::new();
        actual.iter().for_each(|(k, v)| {
            m.insert(k.clone(), v.clone());
        });
        let body: Vec<String> = m.iter().map(|(k, v)| format!("  {}: {}", json!(k), v)).collect();
        std::fs::write(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/corpus-inventory.json"),
            format!("{{\n{}\n}}\n", body.join(",\n")),
        )
        .unwrap();
        return;
    }
    let pinned: BTreeMap<String, Value> =
        atlas_pca::serde_json::from_str::<Map<String, Value>>(PINNED).expect("inventory").into_iter().collect();
    let mut bad = Vec::new();
    for (k, v) in &actual {
        // generated by the reference in CI on every run and never committed: there is nothing stable to pin
        if k == "ref-dpop-rsa" {
            continue;
        }
        match pinned.get(k) {
            None => bad.push(format!("{k}: a corpus with no pinned inventory entry")),
            Some(p) if p != v => bad.push(format!("{k}: pinned {p} but the corpus is {v}")),
            _ => {}
        }
    }
    for k in pinned.keys().filter(|k| !actual.contains_key(*k)) {
        bad.push(format!("{k}: pinned but the corpus is gone"));
    }
    assert!(bad.is_empty(), "{} corpora differ from tests/corpus-inventory.json (refresh with PCA_UPDATE_CORPUS_INVENTORY=1 after checking the replay tests):\n{}", bad.len(), bad.join("\n"));
}
